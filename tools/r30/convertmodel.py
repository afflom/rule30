def load_fixtures():
    return json.loads(FIXTURES.read_text()) if FIXTURES.exists() else []


def resolve(signature_text, lx=None):
    """What `convert.py` says about a signature, ("statement", text) or
    ("refused", message), and the qids of the glossary entries it resolved."""
    from .lexicon import Lexicon
    recording = _Recording(lx or Lexicon())
    conv = convert.Converter(recording, TARGET)
    try:
        term = conv.term(sexpr.parse(signature_text))
        verdict, text = "statement", conv.statement(term)
    except convert.Unsupported as e:
        verdict, text = "refused", str(e)
    return verdict, text, set(recording.seen)


def expected(signature_text, lx=None):
    return resolve(signature_text, lx)[:2]


def fixture_declarations(fixtures, lx=None):
    out = []
    names = []
    for i, fx in enumerate(fixtures, 1):
        nodes, root = encode(sexpr.parse(fx["signature"]))
        name = f"signature{i}"
        names.append(name)
        out.append(definition(name, [], T("Signature"), signature_record(fx["lean"], nodes, root)))
        verdict, text = expected(fx["signature"], lx)
        out.append(theorem(f"converts{i}", call("outcome", call("convert", call(name))),
                           lst([S(verdict)] + [S(c) for c in text], STR)))
    out.append(definition("fixtures", [], L(T("Signature")), lst([call(n) for n in names], T("Signature"))))
    out.append(definition("fixtureCount", [], NAT, {"kind": "primitive", "operation": "length", "result": NAT,
                                                   "arguments": [call("fixtures")]}))
    out.append(theorem("fixtureCountIs", call("fixtureCount"), N(len(fixtures)), "reflexivity"))
    return out


def declarations(fixtures=None, lx=None):
    from .lexicon import Lexicon
    lx = lx or Lexicon()
    fixtures = load_fixtures() if fixtures is None else fixtures
    rows, visible = lexemes(fixtures, lx)
    return data_declarations(rows, visible) + program_declarations() + fixture_declarations(fixtures, lx)


def render(fixtures=None, lx=None):
    from . import lexmod
    return lexmod.module("Convert", declarations(fixtures, lx))


def capture_fixtures(names=FIXTURE_NAMES, **kw):
    """`convert_fixtures.json` from Lean: the signatures of FIXTURE_NAMES as
    `bin/r30 sig` prints them (the research library must be built)."""
    from . import leansig
    sigs = leansig.signatures(list(names), **kw)
    missing = [n for n in names if sigs.get(n) is None]
    if missing:
        raise RuntimeError("Lean does not know: " + ", ".join(missing))
    rows = [{"lean": n, "signature": sexpr.dumps(sigs[n]["type"])} for n in names]
    FIXTURES.write_text(json.dumps(rows, indent=1) + "\n")
    return rows


def sync(fixtures=False):
    if fixtures:
        capture_fixtures()
    MODULE.parent.mkdir(parents=True, exist_ok=True)
    text = render()
    changed = not MODULE.exists() or MODULE.read_text() != text
    if changed:
        MODULE.write_text(text)
    return {"module": str(MODULE.relative_to(repo.ROOT)), "fixtures": len(load_fixtures()), "changed": changed}


def check():
    if not MODULE.exists():
        return {"ok": False, "reason": "rule30-api/src/Convert.lex.tex is missing; run `bin/r30 api sync`"}
    ok = MODULE.read_text() == render()
    if ok:
        return {"ok": True, "reason": None}
    return {"ok": False, "reason": "Convert.lex.tex drifted (convert.py, a fixture statement, or a glossary entry "
                                   "the fixtures resolve changed); run `bin/r30 api sync`"}
