"""The converter from Lean signatures to LexLean statements as a LexLean
semantic module.

`rule30-api/src/Convert.lex.tex` restates `convert.py` (the pure part of
`bin/r30 theorem add`: a Lean declaration type, as `bin/r30 sig` prints it,
to the controlled-English statement the paper carries) in LexLean's
language-1.2 notation, generated by `bin/r30 api sync`:

- the signature language as structures: a `Node` is one cell of a Lean
  s-expression (`pi` with its binder mode, `lam`, `app`, `const`, `local`,
  `nat`, `sort`, and the `cons`/`nil` cells of an argument chain), a
  `Signature` is a node arena with its root;
- the lexicon the converter resolves constants through, as a snapshot: the
  core connectives and sorts, and exactly the glossary entries the fixtures
  resolve (`Lexeme`: surface, frame, arity, precedence, associativity,
  result sort, visibility from the target lexicon), so that a glossary
  change elsewhere leaves the module unchanged, with the converter's own tables
  (`Carrier` for the heterogeneous operator classes, `Hint`, `Rewrite` for
  aliases and definitional rewrites);
- the converter as definitions: `check` (the refusals of the first pass, in
  the order Python raises them), `prop` and `math` (controlled English and
  math islands with precedence-aware parentheses), binder naming as a pure
  function of the arena prefix (`nameAt`), and `convert`, whose result is
  `Out {ok, text}` with `text` the statement, or the refusal, as a list of
  characters;
- decided theorems: for every fixture of `convert_fixtures.json` (real
  signatures captured from Lean with `bin/r30 api sync --fixtures`), the
  kernel decides that `convert` yields exactly the characters the Python
  converter produces, and `fixtureCountIs` fixes their number.

What stays in Python (the boundary, see rule30-api/README.md): reading the
s-expression into the arena and joining the character list into a string
(the pinned LexLean cannot decide an equality on a constructed `String`:
`join` is opaque to the kernel under Lean's module system), the `similar:`
candidates of a refusal (lower-casing), the quoted excerpt in two refusal
messages (`application of a non-constant head`, `cannot translate`), and
the deletion of characters outside `_`, `'`, `✝` and the alphanumerics
from binder names. The target lexicon is fixed to `r30.observation`, the
default of `theorem add`."""

