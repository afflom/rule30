def data_declarations(lexicon_rows, visible):
    """Structures and the tables."""
    out = [
        structure("Node", [("kind", STR), ("atom", STR), ("chars", L(STR)), ("mode", STR), ("left", NAT), ("right", NAT)]),
        structure("Signature", [("lean", STR), ("root", NAT), ("nodes", L(T("Node")))]),
        structure("Lexeme", [("qid", STR), ("qidChars", L(STR)), ("lean", STR), ("surface", STR), ("surfaceChars", L(STR)),
                             ("hasSurface", BOOL), ("frame", STR), ("arity", NAT), ("precedence", NAT),
                             ("associativity", STR), ("sort", STR), ("visible", BOOL), ("builtin", BOOL)]),
        structure("Carrier", [("operation", STR), ("carrier", STR), ("lean", STR), ("typeArguments", NAT)]),
        structure("Hint", [("lean", STR), ("hint", L(STR))]),
        structure("Rewrite", [("lean", STR), ("target", STR), ("targetChars", L(STR))]),
        structure("Binder", [("raw", STR), ("name", L(STR)), ("sort", STR)]),
        structure("Out", [("ok", BOOL), ("text", L(STR))]),
        structure("Found", [("ok", BOOL), ("lexeme", T("Lexeme"))]),
        structure("Carried", [("ok", BOOL), ("lean", STR), ("typeArguments", NAT)]),
        structure("Head", [("kind", STR), ("lexeme", T("Lexeme")), ("skip", NAT), ("text", L(STR))]),
    ]
    chunks = [lexicon_rows[i:i + CHUNK] for i in range(0, len(lexicon_rows), CHUNK)]
    for i, ch in enumerate(chunks):
        out.append(definition(f"lexicon{i}", [], L(T("Lexeme")), lst([lexeme_record(r) for r in ch], T("Lexeme"))))
    body = call("lexicon0")
    for i in range(1, len(chunks)):
        body = lappend(body, call(f"lexicon{i}"), T("Lexeme"))
    out.append(definition("lexicon", [], L(T("Lexeme")), body))
    carriers = []
    for op, table in convert.HOPS.items():
        for carrier, lean in table.items():
            carriers.append(rec("Carrier", operation=S(op), carrier=S(carrier), lean=S(lean),
                                typeArguments=N({"LE.le": 1, "LT.lt": 1, "Neg.neg": 1}.get(op, 3))))
    out.append(definition("carriers", [], L(T("Carrier")), lst(carriers, T("Carrier"))))
    out.append(definition("hints", [], L(T("Hint")),
                          lst([rec("Hint", lean=S(k), hint=chars(v)) for k, v in convert.HINTS.items()], T("Hint"))))
    out.append(definition("aliases", [], L(T("Rewrite")),
                          lst([rec("Rewrite", lean=S(k), target=S(v), targetChars=chars(v)) for k, v in convert.ALIASES.items()], T("Rewrite"))))
    out.append(definition("defeqs", [], L(T("Rewrite")),
                          lst([rec("Rewrite", lean=S(k), target=S(v), targetChars=chars(v)) for k, v in convert.DEFEQ.items()], T("Rewrite"))))
    out.append(definition("reservedSurfaces", [], L(STR), lst([S(s) for s in sorted(convert.RESERVED_SURFACES)], STR)))
    alnum = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"
    out.append(definition("alphanumerics", [], L(STR), lst([S(c) for c in alnum], STR)))
    texts = {
        "textNotVisible": f"` is not visible from {TARGET} (imports: {visible})",
        "textFunctionType": "` has a function type; LexLean's surface is first-order (state the theorem on the orbit's own functions, or keep it as a host lemma)",
        "textReorder": "` is bound after a hypothesis; reorder binders",
        "textImplicit": "` cannot be stated in LexLean; make it explicit",
        "textNotProposition": " is not a proposition",
        "textNoSurface": "` has no math surface; it cannot appear in a statement",
        "textNonConstantHead": "application of a non-constant head",
        "textCannotTranslate": "cannot translate",
        "textNonLiteralOfNat": "non-literal OfNat",
        "textExistsBinder": "existential without a literal binder",
        "textExistsSort": "existential over a non-basic type",
        "textQuantifierIsland": "quantifier inside a math island",
        "textBinderIsland": "binder inside a math island",
        "textNoLexeme": "no lexeme denotes `",
        "textTakes": "` takes ",
        "textArgumentsGot": " arguments, got ",
    }
    for name, text in texts.items():
        out.append(definition(name, [], L(STR), chars(text)))
    return out


def program_declarations():
    """The converter."""
    LS, LN, LB = L(STR), L(T("Node")), L(T("Binder"))
    node = lambda k: call("nodeAt", V("nodes"), k)
    kind = lambda n: proj(n, "kind")
    atom = lambda n: proj(n, "atom")
    is_ = lambda n, k: eqs(kind(n), S(k))
    ok = lambda o: proj(o, "ok")
    text = lambda o: proj(o, "text")
    lit = lambda s: call("accepted", chars(s))
    nodes = V("nodes")
    env = V("env")
    hn = V("hn")

    def cat(*parts):
        node_ = parts[-1]
        for p in reversed(parts[:-1]):
            node_ = call("catOut", p, node_)
        return node_

    d = []
    # --- lists of characters
    d.append(definition("appendChars", [("a", LS), ("b", LS)], LS,
                        match_list(V("a"), V("b"), "h", "t", {"kind": "cons", "head": V("h"), "tail": call("appendChars", V("t"), V("b"))}), "a"))
    d.append(definition("charsEqual", [("a", LS), ("b", LS)], BOOL,
                        match_list(V("a"), match_list(V("b"), B(True), "h2", "t2", B(False)), "h", "t",
                                   match_list(V("b"), B(False), "h2", "t2",
                                              and_(eqs(V("h"), V("h2")), call("charsEqual", V("t"), V("t2"))))), "a"))
    d.append(definition("isEmpty", [("a", LS)], BOOL, match_list(V("a"), B(True), "h", "t", B(False))))
    d.append(definition("memberString", [("x", STR), ("xs", LS)], BOOL,
                        match_list(V("xs"), B(False), "h", "t", or_(eqs(V("x"), V("h")), call("memberString", V("x"), V("t")))), "xs"))
    d.append(definition("memberChars", [("x", LS), ("xs", L(LS))], BOOL,
                        match_list(V("xs"), B(False), "h", "t", or_(call("charsEqual", V("x"), V("h")), call("memberChars", V("x"), V("t")))), "xs"))
    d.append(definition("countOf", [("xs", L(LS))], NAT, match_list(V("xs"), N(0), "h", "t", add(call("countOf", V("t")), N(1))), "xs"))
    d.append(definition("digitOf", [("n", NAT)], STR,
                        cond(*[(eqn(V("n"), N(i)), S(str(i))) for i in range(9)], default=S("9"))))
    d.append(definition("natChars", [("fuel", NAT), ("n", NAT)], LS,
                        match_nat(V("fuel"), chars(""), "f",
                                  if_(ltn(V("n"), N(10)), lst([call("digitOf", V("n"))], STR),
                                      call("appendChars", call("natChars", V("f"), quot(V("n"), N(10))), lst([call("digitOf", rem(V("n"), N(10)))], STR)))), "fuel"))
    d.append(definition("digits", [("n", NAT)], LS, call("natChars", N(32), V("n"))))
    # --- outcomes
    d.append(definition("accepted", [("text", LS)], T("Out"), rec("Out", ok=B(True), text=V("text"))))
    d.append(definition("refused", [("text", LS)], T("Out"), rec("Out", ok=B(False), text=V("text"))))
    d.append(definition("catOut", [("a", T("Out")), ("b", T("Out"))], T("Out"),
                        if_(ok(V("a")), if_(ok(V("b")), call("accepted", call("appendChars", text(V("a")), text(V("b")))), V("b")), V("a"))))
    d.append(definition("wrapParens", [("o", T("Out")), ("needed", BOOL)], T("Out"),
                        if_(V("needed"), cat(lit("("), V("o"), lit(")")), V("o"))))
    # --- the arena
    d.append(definition("noNode", [], T("Node"), NO_NODE))
    d.append(definition("nodeAt", [("nodes", LN), ("k", NAT)], T("Node"),
                        match_list(nodes, call("noNode"), "h", "t", match_nat(V("k"), V("h"), "j", call("nodeAt", V("t"), V("j")))), "nodes"))
    d.append(definition("countNodes", [("nodes", LN)], NAT, match_list(nodes, N(0), "h", "t", add(call("countNodes", V("t")), N(1))), "nodes"))
    d.append(definition("fuelOf", [("nodes", LN)], NAT,
                        add(add(add(call("countNodes", nodes), call("countNodes", nodes)), call("countNodes", nodes)), N(3))))
    d.append(definition("chainLength", [("fuel", NAT), ("nodes", LN), ("c", NAT)], NAT,
                        match_nat(V("fuel"), N(0), "f", if_(is_(node(V("c")), "cons"), add(call("chainLength", V("f"), nodes, proj(node(V("c")), "right")), N(1)), N(0))), "fuel"))
    d.append(definition("chainDrop", [("n", NAT), ("nodes", LN), ("c", NAT)], NAT,
                        match_nat(V("n"), V("c"), "m", call("chainDrop", V("m"), nodes, proj(node(V("c")), "right"))), "n"))
    d.append(definition("chainNth", [("nodes", LN), ("c", NAT), ("n", NAT)], NAT, proj(node(call("chainDrop", V("n"), nodes, V("c"))), "left")))
    d.append(definition("headOf", [("nodes", LN), ("k", NAT)], T("Node"),
                        if_(is_(node(V("k")), "app"), node(proj(node(V("k")), "left")), node(V("k")))))
    d.append(definition("isAppOf", [("nodes", LN), ("k", NAT), ("name", STR)], BOOL,
                        and_(is_(node(V("k")), "app"), and_(is_(call("headOf", nodes, V("k")), "const"), eqs(atom(call("headOf", nodes, V("k"))), V("name"))))))
    d.append(definition("sortQid", [("n", T("Node"))], STR,
                        if_(is_(V("n"), "const"), cond(*[(eqs(atom(V("n")), S(k)), S(q)) for k, q in SORT_QID.items()], default=S("")), S(""))))
    d.append(definition("isVarType", [("n", T("Node"))], BOOL, not_(eqs(call("sortQid", V("n")), S("")))))
