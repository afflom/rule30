# ---------------------------------------------------------------- the data form

STR, BOOL, NAT = {"kind": "string"}, {"kind": "bool"}, {"kind": "nat"}


def L(t):
    return {"kind": "list", "element": t}


def T(name):
    return {"kind": "named", "member": {"name": name}, "arguments": []}


def S(v):
    return {"kind": "string", "value": v}


def B(v):
    return {"kind": "bool", "value": bool(v)}


def N(v):
    return {"kind": "nat", "value": str(v)}


def V(n):
    return {"kind": "var", "name": n}


def call(f, *args):
    return {"kind": "call", "function": {"name": f}, "arguments": list(args)}


def proj(v, f):
    return {"kind": "project", "value": v, "field": f}


def rec(type_, **fields):
    return {"kind": "record", "type": {"name": type_}, "fields": [{"field": k, "value": v} for k, v in fields.items()]}


def if_(c, t, e):
    return {"kind": "if", "condition": c, "then_value": t, "else_value": e}


def eqs(a, b):
    return {"kind": "primitive", "operation": "equal", "result": BOOL, "arguments": [a, b]}


def eqn(a, b):
    return {"kind": "beq", "left": a, "right": b}


def ltn(a, b):
    return {"kind": "blt", "left": a, "right": b}


def and_(a, b):
    return if_(a, b, B(False))


def or_(a, b):
    return if_(a, B(True), b)


def not_(a):
    return if_(a, B(False), B(True))


def add(a, b):
    return {"kind": "add", "left": a, "right": b}


def sub(a, b):
    return {"kind": "primitive", "operation": "subtract", "result": NAT, "arguments": [a, b]}


def quot(a, b):
    return {"kind": "primitive", "operation": "quotient", "result": NAT, "arguments": [a, b, N(0)]}


def rem(a, b):
    return {"kind": "primitive", "operation": "remainder", "result": NAT, "arguments": [a, b, N(0)]}


def lappend(a, b, t):
    return {"kind": "primitive", "operation": "append", "result": L(t), "arguments": [a, b]}


def match_list(s, nil_body, h, t, cons_body):
    return {"kind": "match", "scrutinee": s, "branches": [
        {"constructor": {"name": "List.nil"}, "binders": [], "body": nil_body},
        {"constructor": {"name": "List.cons"}, "binders": [h, t], "body": cons_body}]}


def match_nat(s, zero_body, p, succ_body):
    return {"kind": "match", "scrutinee": s, "branches": [
        {"constructor": {"name": "Nat.zero"}, "binders": [], "body": zero_body},
        {"constructor": {"name": "Nat.succ"}, "binders": [p], "body": succ_body}]}


def chars(text):
    return lst([S(c) for c in text], STR)


def cond(*pairs, default):
    """An if-chain: cond((c1, v1), (c2, v2), default=v)."""
    node = default
    for c, v in reversed(pairs):
        node = if_(c, v, node)
    return node


def definition(name, params, result, body, rec_arg=None):
    d = {"kind": "definition", "name": name, "parameters": [{"name": n, "type": t} for n, t in params],
         "result": result, "axioms": [], "body": body}
    if rec_arg:
        d["recursive_argument"] = rec_arg
    return d


def structure(name, fields):
    return {"kind": "structure", "name": name, "parameters": [], "type_parameters": [],
            "fields": [{"name": n, "type": t} for n, t in fields]}


def theorem(name, left, right, proof="decide"):
    return {"kind": "theorem", "name": name, "parameters": [], "axioms": [],
            "statement": {"kind": "eq", "left": left, "right": right}, "proof": {"kind": proof}}


# ---------------------------------------------------------------- the signature arena

def encode(node):
    """A Lean s-expression as the node arena: index 0 is the shared `nil`
    cell, and a binder's type precedes the binder, which precedes the body,
    so that index order is the order in which `convert.py` assigns binder
    names (`nameAt` recomputes them from the prefix)."""
    nodes = [{"kind": "nil", "atom": "", "mode": "", "left": 0, "right": 0}]

    def cell(kind, atom="", mode="", left=0, right=0):
        nodes.append({"kind": kind, "atom": atom, "mode": mode, "left": left, "right": right})
        return len(nodes) - 1

    def enc(n):
        if not isinstance(n, list):
            return cell("atom", n)
        tag = n[0]
        if tag in ("local", "nat", "sort"):
            return cell(tag, n[1], right=0)
        if tag == "const":
            return cell("const", n[1], right=0)
        if tag == "app":
            head = enc(n[1])
            me = cell("app")
            cells = []
            for a in n[2:]:
                c = cell("cons")
                cells.append((c, enc(a)))
            nxt = 0
            for c, e in reversed(cells):
                nodes[c]["left"], nodes[c]["right"] = e, nxt
                nxt = c
            nodes[me]["left"], nodes[me]["right"] = head, nxt
            return me
        if tag == "pi":
            _, mode, name, ty, body = n
            t = enc(ty)
            me = cell("pi", name, mode)
            b = enc(body)
            nodes[me]["left"], nodes[me]["right"] = t, b
            return me
        if tag == "lam":
            _, name, ty, body = n
            t = enc(ty)
            me = cell("lam", name)
            b = enc(body)
            nodes[me]["left"], nodes[me]["right"] = t, b
            return me
        return cell(tag)
    root = enc(node)
    return nodes, root


def node_record(n):
    return rec("Node", kind=S(n["kind"]), atom=S(n["atom"]), chars=chars(n["atom"]), mode=S(n["mode"]),
               left=N(n["left"]), right=N(n["right"]))


def signature_record(lean, nodes, root):
    return rec("Signature", lean=S(lean), root=N(root), nodes=lst([node_record(n) for n in nodes], T("Node")))


# ---------------------------------------------------------------- the lexicon as data

def result_sort(entry):
    """The carrier of a lexeme's result, as `Converter.sort_of` reads it."""
    if not entry.signature:
        return ""
    node = sexpr.parse(entry.signature)
    while isinstance(node, list) and node and node[0] == "pi":
        node = node[2]
    return sexpr.const_name(node) or ""


class _Recording:
    """A lexicon that remembers the entries the converter resolved."""

    def __init__(self, lx):
        self.lx, self.seen = lx, {}

    def for_lean(self, name, visible=None):
        e = self.lx.for_lean(name, visible)
        if e is not None:
            self.seen[e.qid] = e
        return e

    def get(self, qid):
        e = self.lx.get(qid)
        if e is not None:
            self.seen[e.qid] = e
        return e

    def __getattr__(self, name):
        return getattr(self.lx, name)


def lexemes(fixtures, lx=None):
    """The snapshot of the glossary the module carries, in load order: the
    core connectives and sorts the converter names by qid, and exactly the
    entries `convert.py` resolves on the fixtures. A glossary change that
    touches none of them leaves the module unchanged, so the proof loop
    (`theorem add`) never re-verifies it; `api check` reports a row or a
    fixture statement that drifted."""
    from .lexicon import Lexicon
    lx = lx or Lexicon()
    visible = lx.visible_from(TARGET)
    keep = set(CORE_QID.values()) | {"lexlean.core::exists-op"} | set(SORT_QID.values())
    for fx in fixtures:
        keep |= resolve(fx["signature"], lx)[2]
    rows = []
    for e in lx.entries.values():
        if e.qid not in keep:
            continue
        rows.append({"qid": e.qid, "lean": e.lean_name or "", "surface": e.surface or "", "hasSurface": e.surface is not None,
                     "frame": e.frame or "", "arity": e.arity or 0, "precedence": e.precedence or 0,
                     "associativity": e.associativity or "", "sort": result_sort(e),
                     "visible": e.package in visible, "builtin": e.project == "builtin"})
    return rows, sorted(visible)


