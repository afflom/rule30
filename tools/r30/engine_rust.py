"""The certified runtime of the engine's learning layer: the Rust packages of the
production roots `learnAll` and `schedule` of Engine.lex.tex (`bin/r30 api
production`), driven by a generated harness crate, as `discover_rust.py` drives
the roots of Discovery.lex.tex.

The emitted packages represent a record as a one-constructor enum (`AdtN::C0`
with the fields in order) and a string as `Str`; the harness reads the
package sources to find which enum is the `Weight` record (Str, Str, u64) and
which the `Outcome` record (Str, Str, bool), and whether `run` returns through
the overflow result `R`. It reads one request per line on stdin:

    learn <weights> <outcomes> (<strategy> <family> <value>)* (<strategy> <family> <0|1>)*
    schedule <weights> <family> <count> (<strategy> <family> <value>)* <strategy>*

and prints the learned table (`strategy family value` triples) or the
scheduled ids, or `violation overflow`. `locate` returns `("rust", runner)`
only when a bundle with both packages exists and cargo builds the harness;
otherwise `("python", reason)` and the caller runs the mirror
(`enginemodel.Mirror`), whose agreement with the roots the tests check."""

import json
import re
import shutil

from . import enginemodel as em, production, repo

HARNESS = repo.ROOT / ".r30" / "engine-harness"
CRATES = {name: production.crate_name(name, "engine") for name in em.PRODUCTION_ROOTS}


def bundles():
    root = repo.ROOT / "rule30-api" / ".lexlean" / "production"
    if not root.exists():
        return []
    found = []
    for result in root.glob("*/result.json"):
        pkgs = result.parent / "packages" / "rust-std"
        if all((pkgs / crate / "Cargo.toml").exists() for crate in CRATES.values()):
            found.append(result.parent)
    return sorted(found, key=lambda p: p.stat().st_mtime, reverse=True)


def _shape(lib):
    """(weight enum, outcome enum, run signature) of an emitted package's source."""
    enums = dict((m.group(1), [x.strip() for x in m.group(2).split(",")])
                 for m in re.finditer(r"pub enum (Adt\d+) \{\s*C0\(([^)]*)\),\s*\}", lib))
    weight = next((k for k, v in enums.items() if v == ["Str", "Str", "u64"]), None)
    outcome = next((k for k, v in enums.items() if v == ["Str", "Str", "bool"]), None)
    sig = re.search(r"pub fn run\(([^)]*)\) -> ([^{]+)\{", lib)
    return weight, outcome, (sig.group(2).strip() if sig else "")


def harness_source(bundle):
    pkgs = bundle / "packages" / "rust-std"
    la, sc = CRATES["learnAll"], CRATES["schedule"]
    lw, lo, lret = _shape((pkgs / la / "src" / "lib.rs").read_text())
    sw, _, sret = _shape((pkgs / sc / "src" / "lib.rs").read_text())
    if not (lw and lo and sw):
        raise RuntimeError("the emitted packages do not carry the Weight and Outcome records as expected")
    unwrap = lambda ret: ("match r { Ok(v) => v, Err(_) => return \"violation overflow\".to_string() }"
                          if ret.startswith("R<") else "r")
    return f'''// Generated by tools/r30/engine_rust.py: the certified roots of Engine.lex.tex on stdin.
use std::io::{{self, BufRead, Write}};

fn main() {{
    let worker = std::thread::Builder::new().stack_size(1 << 28).spawn(serve).expect("thread");
    worker.join().expect("the harness thread");
}}

fn serve() {{
    let stdin = io::stdin();
    let mut out = io::BufWriter::new(io::stdout());
    for line in stdin.lock().lines() {{
        let line = line.expect("stdin");
        let words: Vec<&str> = line.split_whitespace().collect();
        if words.is_empty() {{ continue; }}
        let answer = match words[0] {{
            "learn" => learn(&words[1..]),
            "schedule" => schedule(&words[1..]),
            other => format!("error unknown request {{}}", other),
        }};
        writeln!(out, "{{}}", answer).expect("stdout");
    }}
}}

fn learn(w: &[&str]) -> String {{
    let (nw, no) = (w[0].parse::<usize>().unwrap(), w[1].parse::<usize>().unwrap());
    let mut table = {la}::List::nil();
    for i in (0..nw).rev() {{
        let k = 2 + 3 * i;
        table = {la}::List::cons({la}::{lw}::C0({la}::Str::lit(w[k]), {la}::Str::lit(w[k + 1]), w[k + 2].parse().unwrap()), table);
    }}
    let mut outcomes = {la}::List::nil();
    for i in (0..no).rev() {{
        let k = 2 + 3 * nw + 3 * i;
        outcomes = {la}::List::cons({la}::{lo}::C0({la}::Str::lit(w[k]), {la}::Str::lit(w[k + 1]), w[k + 2] == "1"), outcomes);
    }}
    let r = {la}::run(table, outcomes);
    let mut cur = {unwrap(lret)};
    let mut rows = Vec::new();
    while let Some((h, t)) = cur.uncons() {{
        let {la}::{lw}::C0(s, f, v) = h;
        rows.push(format!("{{}} {{}} {{}}", s.text(), f.text(), v));
        cur = t;
    }}
    rows.join(" ")
}}

fn schedule(w: &[&str]) -> String {{
    let (nw, family, na) = (w[0].parse::<usize>().unwrap(), w[1], w[2].parse::<usize>().unwrap());
    let mut table = {sc}::List::nil();
    for i in (0..nw).rev() {{
        let k = 3 + 3 * i;
        table = {sc}::List::cons({sc}::{sw}::C0({sc}::Str::lit(w[k]), {sc}::Str::lit(w[k + 1]), w[k + 2].parse().unwrap()), table);
    }}
    let mut apps = {sc}::List::nil();
    for i in (0..na).rev() {{ apps = {sc}::List::cons({sc}::Str::lit(w[3 + 3 * nw + i]), apps); }}
    let r = {sc}::run(table, {sc}::Str::lit(family), apps);
    let mut cur = {unwrap(sret)};
    let mut ids = Vec::new();
    while let Some((h, t)) = cur.uncons() {{ ids.push(h.text().to_string()); cur = t; }}
    ids.join(" ")
}}
'''


def cargo_toml(bundle):
    pkgs = bundle / "packages" / "rust-std"
    deps = "\n".join(f'{crate} = {{ path = "{pkgs / crate}" }}' for crate in sorted(CRATES.values()))
    return ('[package]\nname = "r30_engine_harness"\nversion = "0.1.0"\nedition = "2021"\npublish = false\n\n'
            '[dependencies]\n' + deps + "\n\n[profile.release]\nopt-level = 3\n")


class Runner:
    def __init__(self, binary, bundle):
        self.binary, self.bundle = binary, bundle
        self.why = f"certified roots of {bundle.name[:12]} (lexlean production), harness built with cargo"

    def _ask(self, line):
        code, out, err = repo.run([str(self.binary)], input=line + "\n", timeout=600)
        if code != 0:
            raise RuntimeError((err or out)[-800:])
        answer = out.strip("\n")
        if answer.startswith(("violation", "error")):
            raise RuntimeError(f"the certified root refused: {answer}")
        return answer

    def learn_all(self, table, outcomes):
        words = ["learn", str(len(table)), str(len(outcomes))]
        words += [str(x) for row in table for x in row]
        words += [x for s, f, ok in outcomes for x in (s, f, "1" if ok else "0")]
        w = self._ask(" ".join(words)).split()
        return [(w[i], w[i + 1], int(w[i + 2])) for i in range(0, len(w), 3)]

    def schedule(self, table, family, applicable):
        words = ["schedule", str(len(table)), family, str(len(applicable))]
        words += [str(x) for row in table for x in row] + list(applicable)
        return self._ask(" ".join(words)).split()


def locate(build=True):
    """('rust', Runner) when the certified packages exist and the harness builds; else ('python', reason)."""
    found = bundles()
    if not found:
        return "python", "no production bundle with the engine packages (run bin/r30 api production)"
    if not shutil.which("cargo"):
        return "python", "cargo is not on PATH"
    bundle = found[0]
    binary = HARNESS / "target" / "release" / "r30_engine_harness"
    stamp = json.dumps({"bundle": str(bundle)})
    if not build:
        current = (HARNESS / "bundle.json").exists() and (HARNESS / "bundle.json").read_text() == stamp
        return ("rust", Runner(binary, bundle)) if current and binary.exists() else ("python", "the harness is not built")
    try:
        files = {HARNESS / "Cargo.toml": cargo_toml(bundle), HARNESS / "src" / "main.rs": harness_source(bundle),
                 HARNESS / "bundle.json": stamp}
    except RuntimeError as e:
        return "python", str(e)
    (HARNESS / "src").mkdir(parents=True, exist_ok=True)
    for path, text in files.items():
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
    code, out, err = repo.run(["cargo", "build", "--release", "--offline", "--quiet"], cwd=HARNESS, timeout=1800)
    if code != 0:
        return "python", "the harness did not build against the emitted packages: " + (err or out).strip()[-300:]
    if not binary.exists():
        return "python", "the harness binary is absent"
    return "rust", Runner(binary, bundle)
