"""The certified runtime of `bin/r30 discover`: the Rust packages of the
production roots of Discovery.lex.tex (`bin/r30 api production`), driven by a
generated harness crate.

`lexlean production build` publishes one package per root under
`rule30-api/.lexlean/production/<result>/packages/rust-std/<crate>/`, each a
safe Rust library with no dependencies whose `run` is the root (its
certificates A, B and E kernel-checked). The harness (`.r30/discover-harness/`,
generated, never committed) depends on the three packages by path and reads
one request per line on stdin:

    columns <width> <base count> <spec count> <words...> <specs...>
    relations <width> <column count> <words...>
    recurrence <bit count> <bits...>

and prints one answer per line: the words of each built column, the masks of
the relations, the connection polynomial, or `violation <code>` when the
checked root refused (the contract violation's two Booleans). `locate`
returns `("rust", runner)` only when a bundle with the three packages exists
and cargo builds the harness; otherwise `("python", reason)`, and the caller
runs the mirror."""

import json
import shutil

from . import discoverymodel as dm, production, repo

HARNESS = repo.ROOT / ".r30" / "discover-harness"
CRATES = {name: production.crate_name(name, "discovery") for name in dm.PRODUCTION_ROOTS}


def bundles():
    """The published bundles that carry every discovery package, newest first."""
    root = repo.ROOT / "rule30-api" / ".lexlean" / "production"
    if not root.exists():
        return []
    found = []
    for result in root.glob("*/result.json"):
        pkgs = result.parent / "packages" / "rust-std"
        if all((pkgs / crate / "Cargo.toml").exists() for crate in CRATES.values()):
            found.append(result.parent)
    return sorted(found, key=lambda p: p.stat().st_mtime, reverse=True)


MAIN_RS = r'''// Generated by tools/r30/discover_rust.py: the certified roots of Discovery.lex.tex on stdin.
use std::io::{self, BufRead, Write};

fn nats<L>(xs: &[u64], nil: fn() -> L, cons: fn(u64, L) -> L) -> L {
    let mut out = nil();
    for x in xs.iter().rev() { out = cons(*x, out); }
    out
}

fn main() {
    // the roots recurse structurally over input-sized lists: run them on a large stack
    let worker = std::thread::Builder::new().stack_size(1 << 30).spawn(serve).expect("thread");
    worker.join().expect("the harness thread");
}

fn serve() {
    let stdin = io::stdin();
    let mut out = io::BufWriter::new(io::stdout());
    for line in stdin.lock().lines() {
        let line = line.expect("stdin");
        let mut it = line.split_whitespace();
        let kind = match it.next() { Some(k) => k.to_string(), None => continue };
        let nums: Vec<u64> = it.map(|x| x.parse().expect("a natural")).collect();
        let answer = match kind.as_str() {
            "columns" => columns(&nums),
            "relations" => relations(&nums),
            "recurrence" => recurrence(&nums),
            other => format!("error unknown request {}", other),
        };
        writeln!(out, "{}", answer).expect("stdout");
    }
}

__ADAPTERS__
'''


def harness_source():
    """The harness's main.rs; the adapters are written against the emitted API
    (`run` of each package, its `List`, products as tuples)."""
    c, r, q = CRATES["buildColumns"], CRATES["findRelations"], CRATES["findRecurrence"]
    adapters = f'''
fn words_c(xs: &[u64]) -> {c}::List<u64> {{ nats(xs, {c}::List::nil, {c}::List::cons) }}
fn words_r(xs: &[u64]) -> {r}::List<u64> {{ nats(xs, {r}::List::nil, {r}::List::cons) }}
fn unlist_c<T: Clone>(l: &{c}::List<T>) -> Vec<T> {{
    let mut out = Vec::new();
    let mut cur = l.clone();
    while let Some((h, t)) = cur.uncons() {{ out.push(h); cur = t; }}
    out
}}
fn unlist_r<T: Clone>(l: &{r}::List<T>) -> Vec<T> {{
    let mut out = Vec::new();
    let mut cur = l.clone();
    while let Some((h, t)) = cur.uncons() {{ out.push(h); cur = t; }}
    out
}}
fn unlist_q<T: Clone>(l: &{q}::List<T>) -> Vec<T> {{
    let mut out = Vec::new();
    let mut cur = l.clone();
    while let Some((h, t)) = cur.uncons() {{ out.push(h); cur = t; }}
    out
}}

fn columns(n: &[u64]) -> String {{
    let (width, nb, ns) = (n[0], n[1] as usize, n[2] as usize);
    let per = (n.len() - 3 - 3 * ns) / nb;
    let mut bases = {c}::List::nil();
    for i in (0..nb).rev() {{ bases = {c}::List::cons(words_c(&n[3 + i * per..3 + (i + 1) * per]), bases); }}
    let off = 3 + nb * per;
    let mut specs = {c}::List::nil();
    for i in (0..ns).rev() {{
        let s = &n[off + 3 * i..off + 3 * i + 3];
        specs = {c}::List::cons((s[0], (s[1], s[2])), specs);
    }}
    match {c}::run(width, bases, specs) {{
        Ok(cols) => unlist_c(&cols).iter().map(|w| unlist_c(w).iter().map(|x| x.to_string()).collect::<Vec<_>>().join(",")).collect::<Vec<_>>().join(" "),
        Err(_) => "violation overflow".to_string(),
    }}
}}

fn relations(n: &[u64]) -> String {{
    let (width, m) = (n[0], n[1] as usize);
    let per = (n.len() - 2) / m;
    let mut cols = {r}::List::nil();
    for i in (0..m).rev() {{ cols = {r}::List::cons(words_r(&n[2 + i * per..2 + (i + 1) * per]), cols); }}
    match {r}::run((width, cols)) {{
        Ok(Ok(rels)) => unlist_r(&rels).iter().map(|m| unlist_r(m).iter().map(|b| if *b {{ '1' }} else {{ '0' }}).collect::<String>()).collect::<Vec<_>>().join(" "),
        Ok(Err((a, b))) => format!("violation {{}}{{}}", a as u8, b as u8),
        Err(_) => "violation overflow".to_string(),
    }}
}}

fn recurrence(n: &[u64]) -> String {{
    let k = n[0] as usize;
    let mut bits = {q}::List::nil();
    for i in (0..k).rev() {{ bits = {q}::List::cons(n[1 + i] == 1, bits); }}
    match {q}::run(bits) {{
        Ok(Ok(c)) => unlist_q(&c).iter().map(|b| if *b {{ '1' }} else {{ '0' }}).collect::<String>(),
        Ok(Err((a, b))) => format!("violation {{}}{{}}", a as u8, b as u8),
        Err(_) => "violation overflow".to_string(),
    }}
}}
'''
    return MAIN_RS.replace("__ADAPTERS__", adapters)


def cargo_toml(bundle):
    pkgs = bundle / "packages" / "rust-std"
    deps = "\n".join(f'{crate} = {{ path = "{pkgs / crate}" }}' for crate in sorted(CRATES.values()))
    return ('[package]\nname = "r30_discover_harness"\nversion = "0.1.0"\nedition = "2021"\npublish = false\n\n'
            '[dependencies]\n' + deps + "\n\n[profile.release]\nopt-level = 3\n")


class Runner:
    """The built harness: one process per request batch."""

    def __init__(self, binary, bundle):
        self.binary, self.bundle = binary, bundle
        self.why = f"certified roots of {bundle.name[:12]} (lexlean production), harness built with cargo"

    def _ask(self, lines, timeout=3600):
        code, out, err = repo.run([str(self.binary)], input="\n".join(lines) + "\n", timeout=timeout)
        if code != 0:
            raise RuntimeError((err or out)[-800:])
        answers = out.splitlines()
        for a in answers:
            if a.startswith(("violation", "error")):
                from .discover import Refused
                raise Refused(f"the certified root refused: {a}")
        return answers

    def build_columns(self, width, bases, specs):
        per = len(bases[0])
        flat = [w for b in bases for w in b] + [x for s in specs for x in s]
        line = f"columns {width} {len(bases)} {len(specs)} " + " ".join(map(str, flat))
        (answer,) = self._ask([line])
        return [[int(x) for x in col.split(",")] if col else [] for col in answer.split(" ")] if answer else []

    def find_relations(self, width, words):
        line = f"relations {width} {len(words)} " + " ".join(str(x) for w in words for x in w)
        (answer,) = self._ask([line])
        return [[int(ch) for ch in m] for m in answer.split()] if answer else []

    def find_recurrences(self, windows):
        lines = [f"recurrence {len(bits)} " + " ".join(map(str, bits)) for bits in windows]
        return [[int(ch) for ch in a] for a in self._ask(lines)]


def locate(build=True):
    """('rust', Runner) when the certified packages exist and the harness builds; else ('python', reason)."""
    found = bundles()
    if not found:
        return "python", "no production bundle with the discovery packages (run bin/r30 api production)"
    if not shutil.which("cargo"):
        return "python", "cargo is not on PATH"
    bundle = found[0]
    HARNESS.mkdir(parents=True, exist_ok=True)
    (HARNESS / "src").mkdir(exist_ok=True)
    stamp = json.dumps({"bundle": str(bundle)})
    files = {HARNESS / "Cargo.toml": cargo_toml(bundle), HARNESS / "src" / "main.rs": harness_source(),
             HARNESS / "bundle.json": stamp}
    for path, text in files.items():
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
    binary = HARNESS / "target" / "release" / "r30_discover_harness"
    if build:
        code, out, err = repo.run(["cargo", "build", "--release", "--offline", "--quiet"], cwd=HARNESS, timeout=1800)
        if code != 0:
            return "python", "the harness did not build against the emitted packages: " + (err or out).strip()[-300:]
    if not binary.exists():
        return "python", "the harness binary is absent"
    return "rust", Runner(binary, bundle)
