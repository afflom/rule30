"""Interface sheets: for one register claim, the labeled interface between the
problem and that claim. A sheet lists the chain of reductions from `problem1`
to the claim, the notions its statement is made of (with their published
defining equations), the exact facts already proved about those notions, and
the handles recorded in the note, so that a session reads what the claim is
made of and what is known about each part without opening a module."""

from . import frontier, leansig, repo

SHEETS = repo.ROOT / "interfaces"


def _constants(node):
    found = set()

    def walk(n):
        if isinstance(n, list):
            if len(n) == 2 and n[0] == "const" and isinstance(n[1], str):
                found.add(n[1])
            for x in n:
                walk(x)
    walk(node)
    return found


def ancestors(claims, cid):
    """The reduction chain(s) from the roots down to `cid`, as a list of ids."""
    by_id = {c["id"]: c for c in claims}
    seen, order = set(), []

    def up(x):
        if x in seen or x not in by_id:
            return
        seen.add(x)
        for d in by_id[x].get("depends", []):
            up(d)
        order.append(x)
    up(cid)
    return order


def notions(lx, lean_name):
    """The Rule30UOR constants of a declaration's type, or of its defining
    equation when it is a predicate; each with its lexeme and definition lemma."""
    sigs = leansig.signatures([lean_name, lean_name + ".eq_1"])
    heads = set()
    for s in sigs.values():
        if s:
            heads |= {n for n in _constants(s["type"]) if n.startswith("Rule30UOR.") and n != lean_name}
    # one level down: the notions the notions are made of (their defining equations)
    if heads:
        deeper = leansig.signatures([h + ".eq_1" for h in sorted(heads)])
        for s in deeper.values():
            if s:
                heads |= {n for n in _constants(s["type"]) if n.startswith("Rule30UOR.") and n != lean_name}
    rows = []
    for h in sorted(heads):
        e = lx.for_lean(h)
        slug = e.id if e else None
        defn = lx.get(f"{e.package}::{slug}-definition") if e else None
        rows.append({"lean": h, "lexeme": e.qid if e else None,
                     "definition": defn.qid if defn else None})
    return rows


def sheet(cid, lx=None, with_related=True):
    from .lexicon import Lexicon
    lx = lx or Lexicon()
    claims = frontier.load()["claim"]
    by_id = {c["id"]: c for c in claims}
    c = by_id.get(cid)
    if c is None:
        raise ValueError(f"no claim {cid}")
    chain = ancestors(claims, cid)
    data = {"id": cid, "status": c["status"], "statement": c["statement"], "lean": c.get("lean"),
            "chain": [{"id": x, "status": by_id[x]["status"], "lean": by_id[x].get("lean")} for x in chain],
            "notions": notions(lx, c["lean"]) if c.get("lean") else [],
            "note": c.get("note")}
    if with_related and data["notions"]:
        data["related"] = {n["lean"]: leansig.mentions([n["lean"]]) for n in data["notions"]}
    return data


def render(data):
    mark = {"open": "?", "proved": "✓", "refuted": "✗", "retired": "-"}
    out = [f"# Interface: {data['id']} [{data['status']}]", "", data["statement"], ""]
    if data.get("lean"):
        out += [f"Lean: `{data['lean']}`", ""]
    out += ["## Chain from the root", ""]
    for x in data["chain"]:
        out.append(f"- [{mark[x['status']]}] {x['id']}" + (f" — `{x['lean']}`" if x.get("lean") else ""))
    out += ["", "## Notions (labels)", ""]
    for n in data["notions"]:
        out.append(f"- `{n['lean']}`" + (f" — lexeme `{n['lexeme']}`" if n["lexeme"] else " — unpublished")
                   + (f", defining equation `{n['definition']}`" if n["definition"] else ""))
    if data.get("related"):
        out += ["", "## Exact facts about each notion", ""]
        for h, rows in data["related"].items():
            out.append(f"### `{h}` ({len(rows)})")
            out += [f"- `{r}`" for r in rows[:60]]
            if len(rows) > 60:
                out.append(f"- … {len(rows) - 60} more")
            out.append("")
    if data.get("note"):
        out += ["## Handles (register note)", "", data["note"], ""]
    out += ["", "_Generated by `bin/r30 interface`; the register is the source._"]
    return "\n".join(out) + "\n"


def write(cid, data=None):
    data = data or sheet(cid)
    SHEETS.mkdir(exist_ok=True)
    path = SHEETS / f"{cid}.md"
    path.write_text(render(data))
    return path
